function add(r, title, labels = [], kw = {}) {
  const i = pid(r);
  if (!passages.has(i)) passages.set(i, { id: i, range: r, title: null, labels: [] });
  const p = passages.get(i);
  if (title && !p.title) p.title = title;
  p.labels = order([...p.labels, ...labels]);
  for (const [k, v] of Object.entries(kw)) if (v != null) p[k] = v;
  return i;
}
