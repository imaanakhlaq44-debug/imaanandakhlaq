// APK-only post-build step: puts a parental gate in front of every link that
// leaves the app.
//
// The Families policy requires a child-directed app to gate links out to the
// open web — social profiles, WhatsApp, the website, an external PDF. The
// payload has dozens of them, mostly in page footers, so gating them one at a
// time would be a list nobody keeps up to date. This intercepts the click
// instead: any <a> pointing at another origin is stopped, a grown-up answers an
// arithmetic question, and only then does the link open.
//
// Like the bottom bar, this only mutates files inside dist/, and the injected
// script does nothing at all outside the APK shell.

const fs = require('fs');
const path = require('path');
const { insertBeforeBodyEnd, insertBeforeHeadEnd } = require('./lib/html-inject.cjs');

const projectRoot = path.join(__dirname, '..');
const distDir = path.join(projectRoot, 'dist');
const jsDir = path.join(distDir, 'kidba_assets', 'js');
const JS_NAME = 'apk-parental-gate.js';

const GATE_JS = `/* APK-only parental gate for links that leave the app. Auto-generated by scripts/apk-parental-gate.cjs */
(function(){
  function isApk(){
    try {
      if (window.Capacitor && (window.Capacitor.isNativePlatform ? window.Capacitor.isNativePlatform() : true)) return true;
    } catch(e){}
    if (location.protocol === 'capacitor:') return true;
    if (location.protocol === 'https:' && location.hostname === 'localhost') return true;
    try {
      if (location.search.indexOf('apkgate=1') !== -1) return true;
      if (localStorage.getItem('apk_parental_gate') === '1') return true;
    } catch(e){}
    return false;
  }
  if (!isApk()) return;
  if (window.__apkParentalGate) return;
  window.__apkParentalGate = true;

  // Which links leave the app. Same-origin pages are the app itself; fonts and
  // stylesheets are <link> elements and never reach a click handler.
  function leavesTheApp(a){
    var raw = a.getAttribute('href') || '';
    if (!/^https?:/i.test(raw)) return null;
    try {
      var u = new URL(raw, location.href);
      if (u.origin === location.origin) return null;
      return u.href;
    } catch(e){ return null; }
  }

  var overlay = null, pending = null, answer = 0;

  function question(){
    var a = 3 + Math.floor(Math.random() * 7);   // 3..9
    var b = 11 + Math.floor(Math.random() * 9);  // 11..19
    answer = a * b;
    return a + ' \\u00d7 ' + b;
  }

  function build(){
    overlay = document.createElement('div');
    overlay.id = 'apkParentalGate';
    overlay.setAttribute('role', 'alertdialog');
    overlay.setAttribute('aria-modal', 'true');
    overlay.style.cssText = 'position:fixed;inset:0;z-index:2147483700;background:rgba(4,8,22,0.92);display:none;align-items:center;justify-content:center;padding:22px';
    overlay.innerHTML =
      '<div style="width:100%;max-width:340px;background:#fff;color:#1E2D5A;border-radius:20px;padding:24px 20px;box-shadow:0 18px 50px rgba(0,0,0,0.55);text-align:center;font-family:Nunito,Arial,sans-serif">' +
        '<div style="font-size:38px;line-height:1">\\ud83d\\udc6a</div>' +
        '<h2 style="margin:8px 0 6px;font-size:19px;font-weight:800">Ask a grown-up</h2>' +
        '<p style="margin:0 0 4px;font-size:13.5px;line-height:1.55;color:#475569">This link opens outside the app, in your browser.</p>' +
        '<p style="margin:0 0 14px;font-size:13.5px;line-height:1.55;color:#475569">A parent or guardian should answer to continue.</p>' +
        '<div id="apkGateQ" style="font-size:24px;font-weight:800;margin-bottom:10px"></div>' +
        '<input id="apkGateA" type="number" inputmode="numeric" autocomplete="off" aria-label="Answer" ' +
          'style="width:100%;box-sizing:border-box;text-align:center;font-size:20px;font-weight:700;padding:12px;border:2px solid #cbd5e1;border-radius:14px;color:#1E2D5A">' +
        '<div id="apkGateErr" style="min-height:18px;margin-top:8px;font-size:12.5px;font-weight:700;color:#b91c1c"></div>' +
        '<button id="apkGateGo" type="button" style="width:100%;margin-top:6px;background:linear-gradient(135deg,#1E2D5A,#D63678);color:#fff;border:none;border-radius:14px;padding:13px 16px;font-size:15px;font-weight:800;cursor:pointer">Open the link</button>' +
        '<button id="apkGateNo" type="button" style="width:100%;margin-top:10px;background:transparent;color:#64748b;border:none;padding:10px;font-size:14px;font-weight:700;cursor:pointer">Stay in the app</button>' +
      '</div>';
    document.body.appendChild(overlay);

    overlay.querySelector('#apkGateNo').addEventListener('click', close);
    overlay.querySelector('#apkGateGo').addEventListener('click', submit);
    overlay.querySelector('#apkGateA').addEventListener('keydown', function(ev){
      if (ev.key === 'Enter') submit();
    });
    overlay.addEventListener('click', function(ev){ if (ev.target === overlay) close(); });
  }

  function close(){
    pending = null;
    if (overlay) overlay.style.display = 'none';
  }

  function submit(){
    var field = overlay.querySelector('#apkGateA');
    var err = overlay.querySelector('#apkGateErr');
    var typed = String(field.value).trim();
    var given = parseInt(typed, 10);
    if (typed !== '' && given === answer) {
      var url = pending;
      close();
      if (url) window.open(url, '_blank', 'noopener');
      return;
    }
    // A wrong answer earns a fresh question, so guessing gets nobody anywhere.
    err.textContent = typed === '' ? 'Please type the answer.' : 'That is not right. Try the new one.';
    overlay.querySelector('#apkGateQ').textContent = question();
    field.value = '';
    field.focus();
  }

  function openGate(url){
    if (!overlay) build();
    pending = url;
    overlay.querySelector('#apkGateQ').textContent = question();
    overlay.querySelector('#apkGateA').value = '';
    overlay.querySelector('#apkGateErr').textContent = '';
    overlay.style.display = 'flex';
    try { overlay.querySelector('#apkGateA').focus(); } catch(e){}
  }

  document.addEventListener('click', function(ev){
    var node = ev.target;
    if (node && node.nodeType !== 1) node = node.parentElement;
    var a = node && node.closest ? node.closest('a[href]') : null;
    if (!a) return;
    var url = leavesTheApp(a);
    if (!url) return;
    ev.preventDefault();
    ev.stopPropagation();
    openGate(url);
  }, true);
})();
`;

function ensureDir(p) { if (!fs.existsSync(p)) fs.mkdirSync(p, { recursive: true }); }

function htmlFiles(dir, out) {
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) htmlFiles(p, out);
    else if (/\.html$/i.test(e.name)) out.push(p);
  });
  return out;
}

function run() {
  if (!fs.existsSync(distDir)) {
    console.error('[apk-parental-gate] dist/ not found. Run vite build first.');
    process.exit(1);
  }
  ensureDir(jsDir);
  fs.writeFileSync(path.join(jsDir, JS_NAME), GATE_JS, 'utf8');

  let injected = 0;
  htmlFiles(distDir, []).forEach(function (file) {
    let html = fs.readFileSync(file, 'utf8');
    if (html.indexOf(JS_NAME) !== -1) return;
    // Each page sits at its own depth, so the src has to be relative to it.
    let src = path.relative(path.dirname(file), path.join(jsDir, JS_NAME)).split(path.sep).join('/');
    if (src.charAt(0) !== '.') src = './' + src;
    const tag = '\n  <script defer src="' + src + '"></script>\n';
    html = insertBeforeBodyEnd(html, tag);
    fs.writeFileSync(file, html, 'utf8');
    injected++;
  });

  console.log('[apk-parental-gate] gate written, ' + injected + ' pages injected.');
}

run();
