// One-off (re-runnable) tool: pulls the web fonts the app uses down from
// Google Fonts into apk_assets/fonts/, so the APK can serve them from disk.
//
// Why: every page of the app asked fonts.googleapis.com for its CSS at load,
// and that <link> is render-blocking. On a slow connection the WebView sat on
// a blank screen until the request came back, then swapped fonts under the
// text a moment later. The website is untouched — scripts/apk-fonts.cjs
// rewrites dist/ at APK build time only.
//
// Run:  node scripts/apk-fonts-fetch.cjs
// Then commit apk_assets/fonts/. Add a family here if a page starts using one.

const fs = require('fs');
const path = require('path');

const OUT_DIR = path.join(__dirname, '..', 'apk_assets', 'fonts');

// Every family + weight any APK page requests (Head.tsx, the dashboards'
// @import lines, apk-splash.cjs and the bottom bar's own sub-pages).
const FAMILIES = [
  'Fredoka+One',
  'Nunito:wght@400;500;600;700;800;900',
  'Poppins:wght@400;500;600;700;800',
  'Sora:wght@400;500;600;700;800',
  'Amiri:wght@400;700',
  'Orbitron:wght@700;800',
];

// Subsets worth shipping: the UI is English, Amiri carries the Arabic of the
// azkar page. The cyrillic, vietnamese and latin-ext subsets go unused.
const SUBSETS = new Set(['latin', 'arabic']);

// A modern Chrome UA is what makes Google answer with woff2 + unicode-range.
const UA = 'Mozilla/5.0 (Linux; Android 13) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Mobile Safari/537.36';

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const url = 'https://fonts.googleapis.com/css2?' + FAMILIES.map((f) => 'family=' + f).join('&') + '&display=swap';
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error('Google Fonts CSS: HTTP ' + res.status);
  const css = await res.text();

  // Blocks look like:  /* latin */ @font-face { font-family: 'Nunito'; ... src: url(https://...woff2) format('woff2'); unicode-range: ... }
  const blockRe = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let out = '/* Generated by scripts/apk-fonts-fetch.cjs — do not edit by hand. */\n';
  let m, kept = 0, skipped = 0;
  const seen = new Set();
  while ((m = blockRe.exec(css))) {
    const subset = m[1];
    let body = m[2];
    if (!SUBSETS.has(subset)) { skipped++; continue; }
    const fam = /font-family:\s*'([^']+)'/.exec(body)[1];
    const weight = (/font-weight:\s*(\d+)/.exec(body) || [, '400'])[1];
    const style = (/font-style:\s*(\w+)/.exec(body) || [, 'normal'])[1];
    const src = /url\((https:[^)]+\.woff2)\)/.exec(body);
    if (!src) { skipped++; continue; }
    const file = (fam + '-' + weight + '-' + style + '-' + subset).replace(/[^A-Za-z0-9-]+/g, '') + '.woff2';
    if (!seen.has(file)) {
      const r = await fetch(src[1], { headers: { 'User-Agent': UA } });
      if (!r.ok) throw new Error(file + ': HTTP ' + r.status);
      fs.writeFileSync(path.join(OUT_DIR, file), Buffer.from(await r.arrayBuffer()));
      seen.add(file);
    }
    body = body.replace(src[1], './' + file);
    out += '/* ' + subset + ' */\n@font-face {' + body + '}\n';
    kept++;
  }
  if (!kept) throw new Error('No @font-face blocks parsed — did Google change the CSS shape?');
  fs.writeFileSync(path.join(OUT_DIR, 'fonts.css'), out);
  let bytes = 0;
  for (const f of fs.readdirSync(OUT_DIR)) bytes += fs.statSync(path.join(OUT_DIR, f)).size;
  console.log('fonts: ' + kept + ' faces kept, ' + skipped + ' subsets skipped, ' + seen.size + ' files, ' + (bytes / 1024).toFixed(0) + ' KB total');
}

main().catch((e) => { console.error(e); process.exit(1); });
